import { Character } from '../types';

export interface JanitorCreationFields {
  characterName: string;
  chatName: string;
  characterBio: string;
  personality: string;
  scenario: string;
  initialMessage: string;
  exampleDialogs: string;
  rating: 'Limited (SFW)' | 'Limitless (NSFW 18+)';
  tags: string[];
}

/**
 * Extracts and structures a Character into Janitor AI's exact 6 Character Creation form fields
 */
export function buildJanitorCreationFields(character: Character): JanitorCreationFields {
  const defaultScenario = character.scenarios?.[0];

  const characterName = character.subtitle && character.subtitle.length < 80
    ? `${character.name} | ${character.subtitle}`
    : character.name;

  const chatName = character.name;

  // 1. Character Bio (Public card description — supports Markdown/HTML & images, not sent to AI)
  const bioParts: string[] = [];
  if (character.shortDescription) {
    bioParts.push(character.shortDescription.trim());
  }
  if (
    character.background &&
    character.background.trim() !== (character.shortDescription || '').trim()
  ) {
    bioParts.push(character.background.trim());
  }
  if (character.creatorNotes) {
    bioParts.push(`\n---\n*${character.creatorNotes.trim()}*`);
  }
  const characterBio = bioParts.join('\n\n') || `${character.name} — Roleplay Character.`;

  // 2. Personality (Core AI instructions, traits, appearance, backstory)
  const personality =
    character.personality?.trim() ||
    `[Character("${character.name}")]\n[Traits("${character.shortDescription || 'Expressive, adaptive'}")]`;

  // 3. Scenario (Foundational context & starting setting)
  const scenario =
    defaultScenario?.description?.trim() ||
    defaultScenario?.scenarioInstructions?.trim() ||
    character.background?.slice(0, 600).trim() ||
    `Roleplay interaction between {{char}} and {{user}}.`;

  // 4. Initial Message (Opening greeting that starts the chat)
  const initialMessage =
    defaultScenario?.openingMessage?.trim() ||
    `*${character.name} looks over at {{user}}.* "Hello."`;

  // 5. Example Dialogs (<START> formatted dialogue exchanges)
  const exampleDialogs =
    character.exampleDialogue?.trim() ||
    `<START>\n{{user}}: "Hello."\n{{char}}: *${character.name} glances over with quiet interest.* "Greetings, {{user}}."`;

  const rating =
    character.contentRating === 'NSFW' || character.contentRating === 'Mature'
      ? 'Limitless (NSFW 18+)'
      : 'Limited (SFW)';

  return {
    characterName,
    chatName,
    characterBio,
    personality,
    scenario,
    initialMessage,
    exampleDialogs,
    rating,
    tags: character.tagSlugs || []
  };
}

/**
 * Generates a formatted Markdown (.md) document ready to copy-paste into Janitor AI's Character Creation page
 */
export function generateJanitorMarkdown(character: Character): string {
  const fields = buildJanitorCreationFields(character);
  const altScenarios = (character.scenarios || []).slice(1);

  const lines: string[] = [
    `# Janitor AI Character Creation Sheet — ${character.name}`,
    `> Generated by **Warden AI**. Copy and paste each section below directly into the corresponding box on Janitor AI's **Create a Character** page.`,
    ``,
    `---`,
    ``,
    `## 1. Character Name`,
    `\`\`\`text`,
    fields.characterName,
    `\`\`\``,
    ``,
    `### Character Chat Name (In-Chat Name)`,
    `\`\`\`text`,
    fields.chatName,
    `\`\`\``,
    ``,
    `### Rating & Tags`,
    `- **Rating:** ${fields.rating}`,
    `- **Tags:** ${fields.tags.map(t => `#${t}`).join(' ') || '#oc #roleplay'}`,
    `- **Avatar URL:** ${character.avatarUrl || 'N/A'}`,
    ``,
    `---`,
    ``,
    `## 2. Character Bio (Public Profile Description — Supports Markdown & Images)`,
    `*(Paste this into the **Character Bio** box. This is visible to users on the card and is not read by the AI.)*`,
    `\`\`\`markdown`,
    fields.characterBio,
    `\`\`\``,
    ``,
    `---`,
    ``,
    `## 3. Personality (Core AI Definition)`,
    `*(Paste this into the **Personality** box. Read by the AI on every turn.)*`,
    `\`\`\`text`,
    fields.personality,
    `\`\`\``,
    ``,
    `---`,
    ``,
    `## 4. Scenario (Setting & Context)`,
    `*(Paste this into the **Scenario** box.)*`,
    `\`\`\`text`,
    fields.scenario,
    `\`\`\``,
    ``,
    `---`,
    ``,
    `## 5. Initial Message (First Message)`,
    `*(Paste this into the **Initial Message** box.)*`,
    `\`\`\`markdown`,
    fields.initialMessage,
    `\`\`\``
  ];

  if (altScenarios.length > 0) {
    lines.push(
      ``,
      `### Alternate Greetings / Additional Scenarios (${altScenarios.length})`,
      ...altScenarios.flatMap((sc, idx) => [
        `#### Alternate #${idx + 1}: ${sc.title}`,
        `\`\`\`markdown`,
        sc.openingMessage,
        `\`\`\``
      ])
    );
  }

  lines.push(
    ``,
    `---`,
    ``,
    `## 6. Example Dialogs`,
    `*(Paste this into the **Example Dialogs** box.)*`,
    `\`\`\`text`,
    fields.exampleDialogs,
    `\`\`\``,
    ``
  );

  return lines.join('\n');
}

/**
 * Triggers a browser download of the character's Janitor AI Markdown (.md) file
 */
export function downloadJanitorMarkdown(character: Character): void {
  const md = generateJanitorMarkdown(character);
  const safeName = (character.name || 'character')
    .toLowerCase()
    .replace(/[^a-z0-9-_]+/g, '-')
    .replace(/^-+|-+$/g, '');
  const blob = new Blob([md], { type: 'text/markdown;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `${safeName || 'character'}-janitorai.md`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

